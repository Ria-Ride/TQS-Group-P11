package pt.ua.deti.tqs.p11.adapter.out.persistence.fleet;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.Instant;
import java.util.UUID;
import pt.ua.deti.tqs.p11.domain.fleet.VehicleState;
import pt.ua.deti.tqs.p11.domain.fleet.VehicleStateChange;

/** JPA mapping of the vehicle_state_changes table. Rows are only inserted. */
@Entity
@Table(name = "vehicle_state_changes")
class VehicleStateChangeJpaEntity {

  /** Generated by the database; also gives the order of changes made at the same instant. */
  @Id
  @GeneratedValue(strategy = GenerationType.IDENTITY)
  private Long id;

  @Column(name = "vehicle_id", nullable = false)
  private UUID vehicleId;

  @Enumerated(EnumType.STRING)
  @Column(name = "from_state", length = 20)
  private VehicleState fromState;

  @Enumerated(EnumType.STRING)
  @Column(name = "to_state", nullable = false, length = 20)
  private VehicleState toState;

  @Column(name = "changed_at", nullable = false)
  private Instant changedAt;

  /** For JPA only. */
  protected VehicleStateChangeJpaEntity() {}

  static VehicleStateChangeJpaEntity from(VehicleStateChange change) {
    VehicleStateChangeJpaEntity entity = new VehicleStateChangeJpaEntity();
    entity.vehicleId = change.vehicleId();
    entity.fromState = change.from();
    entity.toState = change.to();
    entity.changedAt = change.at();
    return entity;
  }

  VehicleStateChange toDomain() {
    return new VehicleStateChange(vehicleId, fromState, toState, changedAt);
  }
}
